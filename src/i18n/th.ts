/** Shape of the dictionary, so a test can assert a key exists. */
export type Dictionary = typeof th;

/**
 * Minimal interpolation: `t('timeline.recalculatedNotice', { count: 3 })`.
 *
 * A lookup is by dot path over the object above, and a missing key returns the
 * path itself rather than `undefined` — a visible `reports.missingKey` in the
 * UI is a far better failure than an empty space.
 */
export function t(path: string, params?: Record<string, string | number>): string {
  const value = path
    .split('.')
    .reduce<unknown>(
      (node, key) => (node && typeof node === 'object' ? (node as Record<string, unknown>)[key] : undefined),
      th,
    );

  if (typeof value !== 'string') return path;
  if (!params) return value;

  return value.replace(/\{(\w+)\}/g, (match, key: string) => {
    const replacement = params[key];
    return replacement === undefined ? match : String(replacement);
  });
}
